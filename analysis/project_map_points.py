def find_sidecar(token):
    hits = sorted(ROOT.glob(f"data/drive/**/DJI_{token}*.MP4.gps.tsv"))
    return hits[0] if hits else None


def main():
    dem = Dem()
    print("name\tvideo\tt\tdrone_lat\tdrone_lon\tdrone_alt\tyaw\tpitch\t"
          "hit_lat\thit_lon\thit_alt\tdist_m\tdrift30_m\toffset_m\tverdict")
    for name, token, t in TASKS:
        side = find_sidecar(token)
        if side is None:
            print(f"{name}\t{token}\t{t}\t" + "\t" * 11 + "miss")
            continue
        video = side.with_suffix("").with_suffix("")  # без .gps.tsv
        rows = load_rows(video)
        lat, lon = at(rows, t, "lat"), at(rows, t, "lon")
        alt = at(rows, t, "alt_m")
        yaw, pitch = at(rows, t, "gb_yaw"), at(rows, t, "gb_pitch")
        yaw = (yaw + 180) % 360 - 180
        direction = ray_dir(yaw, pitch, 0, 0, 0, 0, 1000)
        hit = cast(dem, lat, lon, alt, direction)
        base = f"{name}\t{token}\t{t}\t{lat:.6f}\t{lon:.6f}\t{alt:.0f}\t{yaw:.1f}\t{pitch:.1f}"
        if hit is None:
            print(base + "\t\t\t\t\t\t\tno_hit")
            continue
        la, lo, ground, dist = hit
        drift = 0.0
        for dz in (30, -30):
            h2 = cast(_ShiftDem(dem, dz), lat, lon, alt, direction)
            if h2 is None:
                drift = float("inf")
                continue
            la2, lo2, _, _ = h2
            drift = max(drift, math.hypot(
                (la2 - la) * 111132.0,
                (lo2 - lo) * 111320.0 * math.cos(math.radians(la))))
        offset = math.hypot((la - lat) * 111132.0,
                            (lo - lon) * 111320.0 * math.cos(math.radians(lat)))
        verdict = "ok" if drift <= 30 else "poloho"
        drift_s = "inf" if math.isinf(drift) else f"{drift:.0f}"
        print(base + f"\t{la:.6f}\t{lo:.6f}\t{ground:.0f}\t{dist:.0f}"
                     f"\t{drift_s}\t{offset:.0f}\t{verdict}")


if __name__ == "__main__":
    main()
