СТОЛБЦЫ = ("метка", "класс", "L", "a", "b", "C", "тон", "разброс_L", "разброс_ab",
           "n_пикс", "доля_roi", "кадр", "roi", "правило", "примечание")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "analysis" / "signatures.tsv")
    args = ap.parse_args()
    строки = []
    for метка, класс, кадр, roi, правило, прим in ЗАМЕРЫ:
        r = замер(кадр, roi, правило)
        строки.append("\t".join([
            метка, класс,
            f"{r['L']:.1f}", f"{r['a']:.1f}", f"{r['b']:.1f}", f"{r['C']:.1f}",
            f"{r['тон']:.0f}", f"{r['разброс_L']:.1f}", f"{r['разброс_ab']:.1f}",
            str(r["n"]), f"{r['доля_roi']:.2f}",
            кадр, ",".join(str(v) for v in roi), правило, прим,
        ]))
        print(f"{метка:26s} L={r['L']:5.1f} a={r['a']:6.1f} b={r['b']:6.1f} "
              f"C={r['C']:5.1f} тон={r['тон']:3.0f} n={r['n']}")
    args.out.write_text(ШАПКА + "\t".join(СТОЛБЦЫ) + "\n" + "\n".join(строки) + "\n",
                        encoding="utf-8")
    print(f"записано {len(строки)} сигнатур в {args.out}")


if __name__ == "__main__":
    main()
