def маска(правило, L, a, b, C):
    """Пиксели ROI, проходящие правило вида «C>=15&b<0».

    Свой разбор вместо eval: правило приходит из таблицы выше и попадает в
    файл данных как есть, читатель обязан понимать его без интерпретатора.
    """
    m = np.ones(L.shape, bool)
    поля = {"L": L, "a": a, "b": b, "C": C}
    for член in правило.split("&"):
        for знак in (">=", "<=", ">", "<"):
            имя, _, число = член.partition(знак)
            if not число:
                continue
            if имя not in поля:
                raise ValueError(f"неизвестный канал в правиле: {член}")
            v, порог = поля[имя], float(число)
            m &= {">=": v >= порог, "<=": v <= порог,
                  ">": v > порог, "<": v < порог}[знак]
            break
        else:
            raise ValueError(f"не разобрано правило: {член}")
    return m


def замер(кадр, roi, правило):
    """Медианные L, a, b по пикселям ROI, прошедшим правило, плюс разбросы."""
    путь = ROOT / кадр
    img = cv2.imread(str(путь))
    if img is None:
        raise SystemExit(f"{путь}: не читается")
    x, y, w, h = roi
    lab = cv2.cvtColor(img[y:y + h, x:x + w], cv2.COLOR_BGR2Lab).astype(np.float32)
    L = lab[..., 0] * 100.0 / 255.0
    a = lab[..., 1] - 128.0
    b = lab[..., 2] - 128.0
    C = np.hypot(a, b)
    m = маска(правило, L, a, b, C)
    n = int(m.sum())
    if n == 0:
        raise SystemExit(f"{кадр} {roi} {правило}: правило не отобрало ни одного пикселя")
    mL, ma, mb = (float(np.median(v[m])) for v in (L, a, b))
    return {
        "L": mL, "a": ma, "b": mb,
        "C": math.hypot(ma, mb),
        "тон": math.degrees(math.atan2(mb, ma)) % 360.0,
        # разброс_ab - медиана расстояний до медианы в плоскости a-b: во
        # сколько единиц Lab укладывается сам предмет, без учёта фона.
        "разброс_L": float(np.median(np.abs(L[m] - mL))),
        "разброс_ab": float(np.median(np.hypot(a[m] - ma, b[m] - mb))),
        "n": n,
        "доля_roi": n / float(m.size),
    }


