#!/usr/bin/env python3
"""Разметка выдачи детектора по близости к измеренным цветам вещей группы.

Вход - готовый `detections.tsv` (от `detect.py`) или `tracks.tsv` (от
`video_scan.py`) и `signatures.tsv` (от `measure_signatures.py`). Выход по
умолчанию - тот же файл в том же порядке, с дописанными колонками: расстояние до
ближайшей вещи, до ближайшей ловушки и измеренный цвет.

ПОРЯДОК ПО УМОЛЧАНИЮ НЕ МЕНЯЕТСЯ. Пересортировка включается ключом
--пересортировать, и включать её стоит зная, что она делает. На замерах по
кадрам, которые есть в репозитории, из девяти случаев три улучшились, три
ухудшились и три не сдвинулись, а второй палки (тёмно-серой, её цвет в наборе
сигнатур не представлен) упала с 1-го места на 164-е из 311. Это ровно то, о чём
предупреждает инструкция штаба: цвета курток группы неизвестны, и сортировка по
известным цветам топит неизвестные. Отдельно: на единственном внешне
подтверждённом объекте этого поиска (верёвка, `DJI_20260811204542_0001_Z`, кадр
6135) собственный score детектора тоже оказался серединным - 964-е место из 2650
после слияния каналов. Ни та, ни другая величина не является ранжированием
правдоподобия. Полезная часть этого скрипта - колонка ловушки, которая порядок
не трогает.

РАНЖИРОВАНИЕ НИЧЕГО НЕ УДАЛЯЕТ. На выходе ровно столько же строк, сколько на
входе, и скрипт это проверяет перед записью файла. Причина не в аккуратности,
а в инструкции штаба (`docs/viewing-instructions.md`, п.5): «исходные цвета
курток достоверно неизвестны». Фильтр по цвету выкинул бы в первую очередь то,
чей цвет мы не знаем, то есть самих людей. Менять порядок безопасно, отсеивать -
нет. Кандидаты, у которых цвет измерить не по чему, уходят в конец в исходном
порядке, а не пропадают.

Расстояние. Отдельно считается смещение в плоскости a-b и отдельно по светлоте
L, каждое делится на свой допуск, итог - корень из суммы квадратов. Единица
расстояния - это допуск, а не единица Lab, и печатать её как единицу Lab нельзя.
Допуски взяты из трёх пар «предмет/контроль» в `signatures.tsv` (одна и та же
вещь на двух кадрах, снятых с разницей в минуты): в плоскости a-b вещь уехала на
3,2 / 3,6 / 7,1 единицы Lab, по светлоте на 10,9 / 18,1 / 11,7. Светлота гуляет в
3,5 раза сильнее, потому что её задают экспозиция дрона, экспозиция и уклон
склона, а не сам предмет; отсюда ДОПУСК_AB = 8 и ДОПУСК_L = 28.

В плоскости a-b расстояние евклидово, а не угловое. Тень на снегу в этих кадрах
стоит на том же тоне, что и синий рюкзак (270 против 274 градусов), и отличается
только радиусом (C = 8 против 14). Угловая метрика поставила бы тень на первое
место по сигнатуре рюкзака; евклидова засчитывает ей разницу радиуса.

Бесцветные сигнатуры. У белого стакана радиус C = 3,6: он белый, а не цветной,
и от освещённого снега цветом не отличается ничем. Если считать расстояние и по
нему, наверх любого снежного кадра выходит снег (проверено: 8 из первых 8 строк
кадра 3:20). Поэтому сигнатуры с C ниже ПОРОГ_ЦВЕТА по умолчанию в расчёт
расстояния не берутся, о чём скрипт печатает предупреждение, а ключ
--нейтральные их возвращает. Это ограничение набора цветов, а не отсев
кандидатов: ни одна строка входа при этом не пропадает. Белый стакан этой
сортировкой не поднять, его поднимает собственный score детектора (ранг 7 из 107
в своём кадре) и его же красная маркировка, которая в наборе есть отдельной
цветной сигнатурой.

Ловушки. Строки класса «ловушка» в `signatures.tsv` - это перечисленные в
инструкции гарантированные ложные срабатывания (охра, жёлтая корка на камне,
розовый снег, тень). Расстояние до ближайшей ловушки печатается рядом с
кандидатом и НА ПОРЯДОК НЕ ВЛИЯЕТ. Смысл столбца: если кандидат ближе к охре,
чем к оранжевому предмету, отсматривающий видит это сразу, а решение остаётся за
человеком.

Как берётся цвет кандидата. Маски блоба в `detections.tsv` нет, поэтому цвет
считается по редким пикселям bbox: маска редкости пересчитывается по кадру теми
же порогами, что у `detect.py` (см. `маска_редких`). Медиана по всему bbox
годится хуже: у бирюзовой крышки половину bbox занимает тёмная дыра внутри
кольца, и кандидат уезжает с 1-го места на 28-е. Для `tracks.tsv` кадра на диске
нет, там цвет берётся медианой по bbox кропа и помечается в столбце
«цвет_измерен» словом bbox.

Чего скрипт не делает. Не опознаёт предмет: по цвету находится цвет, а крашеный
камень, лишайник и кусок ткани одного цвета неразличимы. Не перепроверяет score
детектора и не трогает геопривязку.

Использование:
  .venv/bin/python rank_by_signature.py pilot/gt-results/detections.tsv \\
      --кадры pilot/gt --out pilot/gt-results/ranked.tsv
  .venv/bin/python rank_by_signature.py scan-0015/tracks.tsv \\
      --out scan-0015/ranked.tsv          # кропы берутся из scan-0015/crops/
"""

import argparse
import math
from pathlib import Path

import cv2
import numpy as np

from detect import BINS, CROP, DENSITY_THR

ДОПУСК_AB = 8.0      # единиц Lab в плоскости a-b; максимум разъезда предмет/контроль
ДОПУСК_L = 28.0      # единиц Lab по светлоте; в 3,5 раза шире, см. докстроку
ПОРОГ_ЦВЕТА = 8.0    # сигнатура с радиусом C ниже этого от снега не отличима


def читать_сигнатуры(путь):
    """[(метка, класс, L, a, b, C)] из signatures.tsv; комментарии и шапка вон."""
    строки = [s for s in Path(путь).read_text(encoding="utf-8").splitlines()
              if s and not s.startswith("#")]
    шапка = строки[0].split("\t")
    ик = {имя: i for i, имя in enumerate(шапка)}
    вышло = []
    for s in строки[1:]:
        f = s.split("\t")
        вышло.append((f[ик["метка"]], f[ик["класс"]], float(f[ик["L"]]),
                      float(f[ик["a"]]), float(f[ик["b"]]), float(f[ик["C"]])))
    if not вышло:
        raise SystemExit(f"{путь}: ни одной сигнатуры")
    return вышло


def читать_кандидатов(путь):
    """(вид, шапка, [запись]) из detections.tsv или tracks.tsv.

    Формат определяется по содержимому, а не по имени файла: у tracks.tsv есть
    строка заголовка, у detections.tsv её нет.
    """
    строки = [s for s in Path(путь).read_text(encoding="utf-8").splitlines() if s]
    if строки and строки[0].startswith("track\t"):
        шапка = строки[0].split("\t")
        вид, тело = "tracks", строки[1:]
    else:
        шапка = ["кадр", "блоб", "bbox", "площадь", "rgb", "score"]
        вид, тело = "detections", строки
    записи = []
    for i, s in enumerate(тело):
        f = s.split("\t")
        группа, bbox = (f[0], f[2]) if вид == "detections" else (Path(путь).stem, f[4])
        x, y, w, h = (int(v) for v in bbox.split(","))
        записи.append({"i": i, "группа": группа, "bbox": (x, y, w, h), "поля": f})
    return вид, шапка, записи


def файл_кропа(запись, тсв):
    """Путь к кропу трека и левый верхний угол кропа в координатах кадра.

    `video_scan.py` пишет кроп как img[y0:cy+CROP, x0:cx+CROP], где
    x0 = max(0, cx - CROP): у краёв кадра кроп обрезан и предмет в нём не по
    центру, поэтому угол считается той же формулой, а не берётся как CROP.
    """
    t = float(запись["поля"][1])
    имя = f"t{int(запись['поля'][0]):04d}_{int(t) // 60:02d}m{int(t) % 60:02d}s.jpg"
    x, y, w, h = запись["bbox"]
    cx, cy = x + w // 2, y + h // 2
    return тсв.parent / "crops" / имя, (max(0, cx - CROP), max(0, cy - CROP))


def маска_редких(img):
    """Пиксели кадра из редких ячеек Lab-гистограммы, то есть те, что и сработали.

    Восемь строк повторяют начало `detect.anomaly_blobs` (морфология не нужна).
    Повтор, а не вызов: detect.py маску наружу не отдаёт, а править его нельзя.
    Мерить цвет надо именно по этим пикселям: в bbox кольца-крышки половину
    площади занимает тёмная дыра посередине, и медиана по всему bbox уводит
    кандидата с 2-го места на 28-е (проверено на кадре 3:32).
    """
    q = cv2.cvtColor(img, cv2.COLOR_BGR2Lab).astype(np.uint16)
    q[..., 0] = q[..., 0] * BINS[0] // 256
    q[..., 1] = q[..., 1] * BINS[1] // 256
    q[..., 2] = q[..., 2] * BINS[2] // 256
    flat = (q[..., 0] * BINS[1] + q[..., 1]) * BINS[2] + q[..., 2]
    hist = np.bincount(flat.ravel(), minlength=BINS[0] * BINS[1] * BINS[2])
    return (hist[flat].astype(np.float64) / flat.size) < DENSITY_THR


def цвет_bbox(img, маска, bbox):
    """(L, a, b, откуда) по редким пикселям bbox; при их нехватке по всему bbox."""
    x, y, w, h = bbox
    x, y = max(0, x), max(0, y)
    кусок = img[y:y + h, x:x + w]
    if кусок.size == 0:
        return None
    lab = cv2.cvtColor(кусок, cv2.COLOR_BGR2Lab).astype(np.float32)
    m = маска[y:y + h, x:x + w] if маска is not None else None
    откуда = "маска"
    if m is None or m.sum() < 3:
        m = np.ones(lab.shape[:2], bool)
        откуда = "bbox"
    return (float(np.median(lab[..., 0][m])) * 100.0 / 255.0,
            float(np.median(lab[..., 1][m])) - 128.0,
            float(np.median(lab[..., 2][m])) - 128.0, откуда)


def измерить(записи, вид, тсв, кадры):
    """Проставить каждой записи Lab; кто не измерился, помечается и остаётся.

    Для detections.tsv кадр есть целиком, и маска редких пикселей считается по
    нему. Для tracks.tsv на диске только кроп 256x256: гистограмма кропа - это
    не гистограмма кадра, порог плотности на ней значит другое, поэтому там
    цвет берётся медианой по bbox и помечается в столбце «цвет_измерен».
    """
    кэш = {}
    for з in записи:
        if вид == "detections":
            if кадры is None:
                з["lab"] = None
                continue
            путь, сдвиг = кадры / з["группа"], (0, 0)
        else:
            путь, сдвиг = файл_кропа(з, тсв)
        if путь not in кэш:
            img = cv2.imread(str(путь))
            кэш[путь] = (img, маска_редких(img)
                         if img is not None and вид == "detections" else None)
        img, маска = кэш[путь]
        if img is None:
            з["lab"] = None
            continue
        x, y, w, h = з["bbox"]
        замер = цвет_bbox(img, маска, (x - сдвиг[0], y - сдвиг[1], w, h))
        з["lab"] = замер[:3] if замер else None
        з["откуда"] = замер[3] if замер else "нет"


def расстояние(lab, сиг):
    """(итог в допусках, смещение в a-b, смещение по L) до одной сигнатуры."""
    L, a, b = lab
    d_ab = math.hypot(a - сиг[3], b - сиг[4])
    d_L = abs(L - сиг[2])
    return math.hypot(d_ab / ДОПУСК_AB, d_L / ДОПУСК_L), d_ab, d_L


def ближайшая(lab, сигнатуры):
    """(метка, итог, d_ab, d_L) по ближайшей из переданных сигнатур."""
    лучший = None
    for с in сигнатуры:
        итог, d_ab, d_L = расстояние(lab, с)
        if лучший is None or итог < лучший[1]:
            лучший = (с[0], итог, d_ab, d_L)
    return лучший


НОВЫЕ = ["ранг", "ранг_в_группе", "расстояние", "сигнатура", "d_ab", "d_L",
         "ловушка", "d_ловушки", "L", "a", "b", "C", "цвет_измерен"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", type=Path, help="detections.tsv или tracks.tsv")
    ap.add_argument("--сигнатуры", type=Path,
                    default=Path(__file__).resolve().parent / "signatures.tsv")
    ap.add_argument("--кадры", type=Path, default=None,
                    help="каталог с кадрами (нужен для detections.tsv)")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--верх", type=int, default=10, help="сколько строк напечатать")
    ap.add_argument("--нейтральные", action="store_true",
                    help="ранжировать и по бесцветным сигнатурам (белый стакан)")
    ap.add_argument("--пересортировать", action="store_true",
                    help="менять порядок строк по цветовому расстоянию. По умолчанию "
                         "порядок исходного файла сохраняется, а колонки расстояния и "
                         "ловушки только дописываются: на замерах пересортировка "
                         "опускала настоящие предметы (см. docs/colour-signatures.md)")
    args = ap.parse_args()

    все = читать_сигнатуры(args.сигнатуры)
    предметы = [с for с in все if с[1] in ("предмет", "контроль")]
    ловушки = [с for с in все if с[1] == "ловушка"]
    слепые = [с for с in предметы if с[5] < ПОРОГ_ЦВЕТА]
    if слепые and not args.нейтральные:
        предметы = [с for с in предметы if с[5] >= ПОРОГ_ЦВЕТА]
        print(f"сигнатуры {', '.join(с[0] for с in слепые)} почти нейтральны "
              f"(C < {ПОРОГ_ЦВЕТА:.0f}), от снега цветом не отличаются и в "
              f"ранжировании не участвуют: по ним наверх выходит освещённый снег. "
              f"Вернуть ключом --нейтральные. Кандидаты при этом не теряются, "
              f"речь только о том, по каким цветам считать расстояние")
    if not предметы:
        raise SystemExit("не осталось ни одной цветной сигнатуры для ранжирования")

    вид, шапка, записи = читать_кандидатов(args.tsv)
    if вид == "detections" and args.кадры is None:
        raise SystemExit("для detections.tsv нужен --кадры: цвет берётся из кадра")
    измерить(записи, вид, args.tsv, args.кадры)

    сцветом, безцвета = [], []
    for з in записи:
        if з["lab"] is None:
            безцвета.append(з)
            continue
        метка, итог, d_ab, d_L = ближайшая(з["lab"], предметы)
        з.update(метка=метка, итог=итог, d_ab=d_ab, d_L=d_L)
        з["ловушка"] = ближайшая(з["lab"], ловушки) if ловушки else None
        сцветом.append(з)
    if args.пересортировать:
        сцветом.sort(key=lambda з: (з["итог"], з["i"]))

    # Без пересортировки строки идут ровно в порядке исходного файла: тогда
    # выходной файл - это входной с дописанными колонками, и его можно
    # подложить вместо исходного, ничего не потеряв и никого не подвинув.
    порядок = (сцветом + безцвета) if args.пересортировать else записи

    в_группе = {}
    строки = []
    for з in порядок:
        г = з["группа"]
        в_группе[г] = в_группе.get(г, 0) + 1
        if "итог" in з:
            L, a, b = з["lab"]
            лов = з["ловушка"]
            новые = [f"{з['итог']:.3f}", з["метка"], f"{з['d_ab']:.1f}",
                     f"{з['d_L']:.1f}",
                     лов[0] if лов else "", f"{лов[1]:.3f}" if лов else "",
                     f"{L:.1f}", f"{a:.1f}", f"{b:.1f}", f"{math.hypot(a, b):.1f}",
                     з["откуда"]]
        else:
            новые = ["", "", "", "", "", "", "", "", "", "", "нет"]
        строки.append("\t".join([str(len(строки) + 1), str(в_группе[г])] + новые
                                + з["поля"]))

    # Не assert: с ключом -O он исчезает, а это то самое свойство, ради
    # которого пересортировка вообще допущена к поисковым данным.
    if len(строки) != len(записи):
        raise RuntimeError(f"ранжирование потеряло кандидатов: было "
                           f"{len(записи)}, стало {len(строки)}")
    args.out.write_text("\t".join(НОВЫЕ + шапка) + "\n" + "\n".join(строки) + "\n",
                        encoding="utf-8")
    print(f"{args.tsv.name}: {len(записи)} кандидатов, цвет измерен у "
          f"{len(сцветом)}, без цвета {len(безцвета)} (оставлены в конце)")
    for s in строки[:args.верх]:
        f = s.split("\t")
        print(f"  {f[0]:>4} {f[3]:24s} d={f[2]:>6}  ловушка {f[6]:24s} d={f[7]:>6}"
              f"  {' '.join(з for з in f[len(НОВЫЕ):len(НОВЫЕ) + 3])}")
    print(f"записано {args.out}")


if __name__ == "__main__":
    main()
